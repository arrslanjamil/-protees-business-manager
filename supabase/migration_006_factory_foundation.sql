-- Protees Business Manager — Factory / Unit Production module, Phase 1
-- Adds: Factory-only authentication (profiles + role), Product setup
-- (sizes/colors/operations/rate history), and Production Plans.
--
-- IMPORTANT — scope of auth: this ONLY gates the new /factory/* routes.
-- Every existing table (employees, advances, expenses, salary_payments,
-- unit_payments, etc.) is untouched and keeps its current "allow all"
-- policies exactly as-is. This migration adds new tables only — nothing
-- existing is altered, dropped, or renamed. Safe to re-run.

-- ---------------------------------------------------------------------------
-- Factory user profiles — one row per Supabase Auth user, added by a
-- trigger the moment they sign up. `role` starts NULL ("pending approval")
-- until an admin assigns one from the Team Members screen.
-- ---------------------------------------------------------------------------
create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  role text check (role in ('admin', 'cutting_head', 'stitching_head', 'quality_head', 'store_manager')),
  created_at timestamptz not null default now()
);

create or replace function public.factory_role()
returns text
language sql
security definer
stable
set search_path = public
as $$
  select role from profiles where id = auth.uid();
$$;

create or replace function public.handle_new_factory_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', new.email), null)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_factory_user();

alter table profiles enable row level security;
drop policy if exists "read own or admin reads all" on profiles;
drop policy if exists "admin writes all" on profiles;
create policy "read own or admin reads all" on profiles
  for select using (auth.uid() = id or factory_role() = 'admin');
create policy "admin writes all" on profiles
  for update using (factory_role() = 'admin') with check (factory_role() = 'admin');

