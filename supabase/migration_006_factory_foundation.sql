-- ---------------------------------------------------------------------------
-- Products — admin-configured. `production_type` decides whether a plan
-- for this product routes through Digital Print before Cutting.
-- ---------------------------------------------------------------------------
create table if not exists products (
  id bigint generated by default as identity primary key,
  name text not null,
  picture_url text,
  production_type text not null default 'normal' check (production_type in ('normal', 'digital_print')),
  size_group text not null default 'adult' check (size_group in ('adult', 'kids')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists product_sizes (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  size_label text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  unique (product_id, size_label)
);

create table if not exists product_colors (
  product_id bigint not null references products(id) on delete cascade,
  color_id bigint not null references colors(id) on delete cascade,
  primary key (product_id, color_id)
);

-- Operations are grouped under a free-text department label (Overlock,
-- Flat Lock, Singer, Clipping, ...) chosen per product by Admin — never a
-- fixed list, since different products need entirely different operations.
create table if not exists product_operations (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  department_label text not null,
  operation_name text not null,
  sort_order int not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Rate history: a rate is NEVER updated in place. Changing a rate inserts a
-- new row with effective_from = now(); the "current" rate is the latest row
-- per operation. Historical production always snapshots the rate that was
-- current at completion time, so old records never move.
create table if not exists product_operation_rates (
  id bigint generated by default as identity primary key,
  product_operation_id bigint not null references product_operations(id) on delete cascade,
  rate numeric(12,2) not null check (rate >= 0),
  effective_from timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists idx_product_operation_rates_op on product_operation_rates(product_operation_id, effective_from desc);

create or replace view product_operation_current_rates as
select distinct on (product_operation_id)
  product_operation_id,
  rate,
  effective_from
from product_operation_rates
order by product_operation_id, effective_from desc;

-- ---------------------------------------------------------------------------
-- Production Plans — Admin creates. Only relevant (configured) sizes for
-- the chosen product should be offered by the UI.
-- ---------------------------------------------------------------------------
create table if not exists production_plans (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id),
  color_id bigint references colors(id),
  production_type text not null default 'normal' check (production_type in ('normal', 'digital_print')),
  plan_date date not null default current_date,
  expected_completion_date date,
  remarks text,
  status text not null default 'pending' check (status in ('pending', 'in_progress', 'completed', 'cancelled')),
  created_by uuid references profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists production_plan_sizes (
  id bigint generated by default as identity primary key,
  production_plan_id bigint not null references production_plans(id) on delete cascade,
  size_label text not null,
  planned_qty int not null check (planned_qty >= 0),
  unique (production_plan_id, size_label)
);

create index if not exists idx_production_plans_status on production_plans(status);
create index if not exists idx_production_plan_sizes_plan on production_plan_sizes(production_plan_id);

-- ---------------------------------------------------------------------------
-- Row Level Security — factory tables only. Any signed-in user with an
-- approved role (profiles.role is not null) can read; only admin can write
-- product/operation/rate/plan configuration, matching "workers never touch
-- rates" at the database level, not just in the UI.
-- ---------------------------------------------------------------------------
alter table colors enable row level security;
alter table products enable row level security;
alter table product_sizes enable row level security;
alter table product_colors enable row level security;
alter table product_operations enable row level security;
alter table product_operation_rates enable row level security;
alter table production_plans enable row level security;
alter table production_plan_sizes enable row level security;

