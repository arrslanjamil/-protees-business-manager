-- Protees Business Manager — main-app authentication + full audit trail
--
-- Adds:
--   1. app_users: maps a fixed username (aqeel/arslan) to a Supabase Auth
--      account, so the main app can offer username-based login while
--      Supabase Auth itself still authenticates by email under the hood.
--   2. audit_log: an append-only record of every create/update/delete
--      across the business tables, including a full snapshot of deleted
--      rows (which otherwise vanish with no trace).
--   3. created_by_user_id / created_by_username / updated_by_user_id /
--      updated_by_username / updated_at columns on every business table,
--      auto-stamped by a trigger — no frontend code has to set these.
--   4. RLS on the business tables tightened from "allow all" to
--      "must be a row in app_users" — closing the anon-key-can-write-
--      anything gap now that the app has real logins.
--
-- Safe to re-run: every statement is idempotent (IF NOT EXISTS / OR
-- REPLACE / DROP POLICY IF EXISTS). Existing rows are untouched — the new
-- columns come in NULL for pre-existing records, which is expected (see
-- migration notes shared with the user).
--
-- Does NOT touch: the Factory module (profiles, colors, products,
-- product_sizes, product_colors, product_operations,
-- product_operation_rates, production_plans, production_plan_sizes) or
-- its RLS/auth — that stays exactly as it is.

-- ---------------------------------------------------------------------------
-- 1. app_users
-- ---------------------------------------------------------------------------
create table if not exists app_users (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text not null,
  email text not null,
  created_at timestamptz not null default now()
);

-- SECURITY DEFINER so it bypasses RLS on app_users internally — used by
-- every policy below instead of a raw "select id from app_users" subquery.
-- That raw form would re-trigger app_users' own RLS policy every time it's
-- evaluated (including from app_users' own policy), causing Postgres error
-- 42P17 "infinite recursion detected in policy for relation app_users".
create or replace function public.is_app_user()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (select 1 from app_users where id = auth.uid());
$$;

alter table app_users enable row level security;
drop policy if exists "allowed users read directory" on app_users;
create policy "allowed users read directory" on app_users
  for select using (is_app_user());

-- Resolves username -> email for the login screen, callable *before* the
-- user is authenticated (grant to anon). Returns nothing for an unknown
-- username. security definer so it can read app_users regardless of the
-- caller's own row-level access (there isn't one yet, pre-login).
create or replace function public.resolve_login_email(p_username text)
returns text
language sql
security definer
stable
set search_path = public
as $$
  select email from app_users where username = lower(trim(p_username));
$$;
grant execute on function public.resolve_login_email(text) to anon, authenticated;

