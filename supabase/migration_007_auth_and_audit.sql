-- Helper used by the audit trigger to resolve "who is doing this write".
create or replace function public.current_app_username()
returns text
language sql
security definer
stable
set search_path = public
as $$
  select username from app_users where id = auth.uid();
$$;

-- ---------------------------------------------------------------------------
-- 2. audit_log — append-only, written only by the trigger below (security
--    definer), never directly by the app.
-- ---------------------------------------------------------------------------
create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text not null,
  action text not null check (action in ('create', 'update', 'delete')),
  performed_by uuid,
  performed_by_username text,
  performed_at timestamptz not null default now(),
  old_data jsonb,
  new_data jsonb
);
create index if not exists idx_audit_log_table_record on audit_log(table_name, record_id);
create index if not exists idx_audit_log_performed_at on audit_log(performed_at desc);

alter table audit_log enable row level security;
drop policy if exists "allowed users read audit log" on audit_log;
create policy "allowed users read audit log" on audit_log
  for select using (is_app_user());

-- ---------------------------------------------------------------------------
-- 3. Reusable trigger: stamps created_by_*/updated_by_* on the row AND
--    writes an audit_log entry, for insert/update/delete alike.
-- ---------------------------------------------------------------------------
create or replace function public.stamp_and_log_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  uname text := current_app_username();
begin
  if tg_op = 'INSERT' then
    new.created_by_user_id := auth.uid();
    new.created_by_username := uname;
    insert into audit_log (table_name, record_id, action, performed_by, performed_by_username, new_data)
      values (tg_table_name, new.id::text, 'create', auth.uid(), uname, to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    new.updated_by_user_id := auth.uid();
    new.updated_by_username := uname;
    new.updated_at := now();
    insert into audit_log (table_name, record_id, action, performed_by, performed_by_username, old_data, new_data)
      values (tg_table_name, new.id::text, 'update', auth.uid(), uname, to_jsonb(old), to_jsonb(new));
    return new;
  elsif tg_op = 'DELETE' then
    insert into audit_log (table_name, record_id, action, performed_by, performed_by_username, old_data)
      values (tg_table_name, old.id::text, 'delete', auth.uid(), uname, to_jsonb(old));
    return old;
  end if;
  return null;
end;
$$;

