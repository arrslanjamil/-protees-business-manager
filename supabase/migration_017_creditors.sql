create policy "authenticated app users only" on creditor_bills for all using (is_app_user()) with check (is_app_user());

drop policy if exists "authenticated app users only" on creditor_payments;
create policy "authenticated app users only" on creditor_payments for all using (is_app_user()) with check (is_app_user());
