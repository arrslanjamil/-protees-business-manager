-- ---------------------------------------------------------------------------
-- 3. Reusable trigger: stamps created_by_*/updated_by_* on the row AND
--    writes an audit_log entry, for insert/update/delete alike.
-- ---------------------------------------------------------------------------
create or replace function public.stamp_and_log_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  uname text := current_app_username();
begin
  if tg_op = 'INSERT' then
    new.created_by_user_id := auth.uid();
    new.created_by_username := uname;
    insert into audit_log (table_name, record_id, action, performed_by, performed_by_username, new_data)
      values (tg_table_name, new.id::text, 'create', auth.uid(), uname, to_jsonb(new));
    return new;
  elsif tg_op = 'UPDATE' then
    new.updated_by_user_id := auth.uid();
    new.updated_by_username := uname;
    new.updated_at := now();
    insert into audit_log (table_name, record_id, action, performed_by, performed_by_username, old_data, new_data)
      values (tg_table_name, new.id::text, 'update', auth.uid(), uname, to_jsonb(old), to_jsonb(new));
    return new;
  elsif tg_op = 'DELETE' then
    insert into audit_log (table_name, record_id, action, performed_by, performed_by_username, old_data)
      values (tg_table_name, old.id::text, 'delete', auth.uid(), uname, to_jsonb(old));
    return old;
  end if;
  return null;
end;
$$;

