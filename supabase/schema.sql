-- ---------------------------------------------------------------------------
-- Khadim Hussain Account — a running ledger of money given to Khadim
-- Hussain for unit material purchases (Payment Given) vs. bills he submits
-- against it (Bill Submitted). Balance = payments given - bills submitted.
-- ---------------------------------------------------------------------------
create table if not exists khadim_transactions (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('payment_given', 'bill_submitted')),
  date date not null default current_date,
  amount numeric(12,2) not null check (amount > 0),
  notes text,
  description text,
  created_at timestamptz not null default now()
);
create index if not exists idx_khadim_transactions_date on khadim_transactions(date);

-- ---------------------------------------------------------------------------
-- Salary payments — Cutting Department, monthly.
-- Net = base + overtime - deduction (computed by the app on insert).
-- ---------------------------------------------------------------------------
create table if not exists salary_payments (
  id bigint generated by default as identity primary key,
  employee_name text not null,
  base_amount numeric(12,2) not null,
  overtime_amount numeric(12,2) not null default 0,
  deduction_amount numeric(12,2) not null default 0,
  net_amount numeric(12,2) not null,
  month int not null check (month between 1 and 12),
  year int not null,
  payment_date date not null default current_date,
  notes text,
  created_at timestamptz not null default now()
);
alter table salary_payments add column if not exists overtime_amount numeric(12,2) not null default 0;

-- ---------------------------------------------------------------------------
-- Unit payments — Protees Unit, bi-weekly.
-- Net = total - advance given (computed by the app on insert).
-- ---------------------------------------------------------------------------
create table if not exists unit_payments (
  id bigint generated by default as identity primary key,
  supervisor_name text not null,
  payment_date date not null default current_date,
  period_start date not null,
  period_end date not null,
  total_amount numeric(12,2) not null default 0,
  overtime_amount numeric(12,2) not null default 0,
  advance_given numeric(12,2) not null default 0,
  net_amount numeric(12,2) not null default 0,
  unit_expenses_during_period numeric(12,2) not null default 0,
  notes text,
  month int not null,
  year int not null,
  created_at timestamptz not null default now()
);
alter table unit_payments add column if not exists overtime_amount numeric(12,2) not null default 0;

-- ---------------------------------------------------------------------------
-- Advance deductions — links a payment (salary OR unit) back to the
-- advance(s) it paid down. Exactly one of salary_payment_id / unit_payment_id
-- is set per row.
-- ---------------------------------------------------------------------------
create table if not exists advance_deductions (
  id bigint generated by default as identity primary key,
  advance_id bigint references advances(id) on delete set null,
  employee_name text not null,
  department text not null default 'cutting_department',
  salary_payment_id bigint references salary_payments(id) on delete cascade,
  unit_payment_id bigint references unit_payments(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  date date not null default current_date,
  created_at timestamptz not null default now()
);
alter table advance_deductions add column if not exists department text not null default 'cutting_department';
alter table advance_deductions add column if not exists unit_payment_id bigint references unit_payments(id) on delete cascade;

-- ---------------------------------------------------------------------------
-- Units — legacy branch/location registry (kept for continuity; the Protees
-- Unit module above is now the primary way this business is modeled).
-- ---------------------------------------------------------------------------
create table if not exists units (
  id bigint generated by default as identity primary key,
  name text not null,
  location text,
  created_at timestamptz not null default now()
);

create index if not exists idx_advances_employee_name on advances(employee_name);
create index if not exists idx_advances_department on advances(department);
create index if not exists idx_salary_payments_employee_name on salary_payments(employee_name);
create index if not exists idx_advance_deductions_employee_name on advance_deductions(employee_name);
create index if not exists idx_advance_deductions_department on advance_deductions(department);
create index if not exists idx_unit_payments_supervisor_name on unit_payments(supervisor_name);
create index if not exists idx_unit_payments_period on unit_payments(period_start, period_end);

-- ---------------------------------------------------------------------------
-- View: outstanding advance balance per (name, department)
-- ---------------------------------------------------------------------------
create or replace view advance_balance_by_name as
select
  coalesce(adv.employee_name, ded.employee_name) as name,
  coalesce(adv.department, ded.department) as department,
  coalesce(adv.total_advanced, 0) as total_advanced,
  coalesce(ded.total_deducted, 0) as total_deducted,
  coalesce(adv.total_advanced, 0) - coalesce(ded.total_deducted, 0) as balance
from (
  select employee_name, department, sum(amount) as total_advanced
  from advances
  group by employee_name, department
) adv
full outer join (
  select employee_name, department, sum(amount) as total_deducted
  from advance_deductions
  group by employee_name, department
) ded on ded.employee_name = adv.employee_name and ded.department = adv.department;

