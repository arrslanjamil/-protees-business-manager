-- Protees Business Manager — full schema
-- Two business units:
--   Protees Unit        — one supervisor, bi-weekly payments, unit expenses
--   Cutting Department   — employees, monthly salary + overtime + advances
-- No employee_id-style foreign keys for people — names (text) are the join
-- key everywhere, matching how this app's data is actually keyed. Safe to
-- run on a fresh database or on top of the existing tables — every
-- statement is idempotent.

create table if not exists employees (
  id bigint generated by default as identity primary key,
  name text not null,
  salary numeric(12,2) not null default 0,
  join_date date,
  created_at timestamptz not null default now()
);
alter table employees add column if not exists join_date date;

create table if not exists supervisors (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Advances — shared by both departments, disambiguated by `department`.
-- ---------------------------------------------------------------------------
create table if not exists advances (
  id bigint generated by default as identity primary key,
  employee_name text not null,
  department text not null default 'cutting_department',
  amount numeric(12,2) not null check (amount > 0),
  payment_date date not null default current_date,
  notes text,
  created_at timestamptz not null default now()
);
alter table advances add column if not exists department text not null default 'cutting_department';
alter table advances add column if not exists notes text;
alter table advances drop constraint if exists advances_department_check;
alter table advances add constraint advances_department_check
  check (department in ('cutting_department', 'protees_unit'));

-- ---------------------------------------------------------------------------
-- Unit Expenses (Protees Unit) — table name stays `expenses` for continuity.
-- ---------------------------------------------------------------------------
create table if not exists expenses (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Other Expenses',
  amount numeric(12,2) not null check (amount > 0),
  date date not null default current_date,
  notes text,
  created_at timestamptz not null default now()
);
alter table expenses add column if not exists category text not null default 'Other Expenses';
alter table expenses add column if not exists notes text;
-- Categories are database-driven (see expense_categories below) — no fixed
-- check constraint on this column.
alter table expenses drop constraint if exists expenses_category_check;

-- ---------------------------------------------------------------------------
-- Expense categories — database-driven, so new categories added from the
-- app (via "+ Add New Category") need no code changes.
-- ---------------------------------------------------------------------------
create table if not exists expense_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
