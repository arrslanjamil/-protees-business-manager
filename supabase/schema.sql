-- Master Data Engine (see migration_016_master_data.sql)
-- Protees Business Manager — Master Data Engine.
--
-- A generic, admin-configurable dropdown system. Every "type" (Creditor
-- Categories, Payment Methods, Colors, Units, ...) is a fixed slot defined
-- here in code — but the VALUES inside each slot are fully dynamic: admin
-- can create/rename/archive them from the Settings screen with no
-- developer/deploy step required. This is the same trade-off every real
-- ERP makes (Odoo, Shopify, etc. have fixed models with dynamic records) —
-- a fully meta-meta system (dynamic types too) would add complexity with
-- no real benefit, since the UI needs a label/grouping per type anyway.
--
-- Safe to re-run.

create table if not exists master_data_types (
  key text primary key,
  label text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists master_data_items (
  id bigint generated by default as identity primary key,
  type_key text not null references master_data_types(key) on delete cascade,
  name text not null,
  is_active boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  created_by_user_id uuid,
  created_by_username text,
  updated_by_user_id uuid,
  updated_by_username text,
  updated_at timestamptz,
  unique (type_key, name)
);
create index if not exists idx_master_data_items_type on master_data_items(type_key);

drop trigger if exists audit_master_data_items on master_data_items;
create trigger audit_master_data_items before insert or update or delete on master_data_items for each row execute function stamp_and_log_audit();

